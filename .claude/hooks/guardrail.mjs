#!/usr/bin/env node
// Repo guardrail rendered by core:forge. Reads "guardrails" from .claude/forge.json.
//   As a PreToolUse hook (payload on stdin): a matching deny rule blocks the tool call; a
//   matching warn rule adds the rule to the model's context. Deny wins over warn whatever the
//   order. Any error allows the call: a broken hook never blocks the repo.
//   With --scan: checks every git-tracked file against the rules for Write/Edit and exits 1
//   on a deny match, so CI and the reviewer catch what was not written through Claude.
// path rules glob the repo-relative path (* within a segment, ** across segments).
// content rules are regexes over the written text: the whole tool_input except the path,
// since Write/Edit field names are not documented. pathGlob limits a content rule to paths.
import { execFileSync } from "node:child_process";
import { readFileSync, realpathSync } from "node:fs";
import { isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULTS = { block: "Blocked by repo rule", warn: "Repo rule" };

export function globToRegExp(glob) {
  let re = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      re += glob[i + 2] === "/" ? "(?:.*/)?" : ".*";
      i += glob[i + 2] === "/" ? 2 : 1;
    } else if (c === "*") re += "[^/]*";
    else if (c === "?") re += "[^/]";
    else re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${re}$`);
}

const globMatch = (glob, path) => globToRegExp(glob).test(path) || (!glob.includes("/") && globToRegExp(glob).test(path.split("/").at(-1)));

export function matches(rule, { path, content }) {
  if (rule.match === "path") return Boolean(path) && globMatch(rule.pattern, path);
  if (rule.match !== "content" || !content) return false;
  if (rule.pathGlob && !(path && globMatch(rule.pathGlob, path))) return false;
  return new RegExp(rule.pattern).test(content);
}

// The decision for one tool call: { action: "deny" | "warn", rule } or null.
export function decide(rules, tool, target) {
  const hits = rules.filter((r) => r.tools?.includes(tool) && matches(r, target));
  return hits.find((r) => r.action === "deny") ? { action: "deny", rule: hits.find((r) => r.action === "deny").rule }
    : hits.length ? { action: "warn", rule: hits[0].rule } : null;
}

function load(root) {
  const spec = JSON.parse(readFileSync(join(root, ".claude", "forge.json"), "utf8"));
  return { rules: spec.guardrails ?? [], labels: { ...DEFAULTS, ...spec.labels } };
}

function hook(input) {
  const payload = JSON.parse(input);
  const root = process.env.CLAUDE_PROJECT_DIR || payload.cwd || process.cwd();
  const { rules, labels } = load(root);
  const ti = payload.tool_input ?? {};
  const file = ti.file_path ?? ti.notebook_path ?? "";
  const path = file ? (isAbsolute(file) ? relative(root, file) : file).split("\\").join("/") : "";
  const { file_path, notebook_path, ...rest } = ti;
  const verdict = decide(rules, payload.tool_name, { path, content: JSON.stringify(rest) });
  if (!verdict) return "";
  const output = verdict.action === "deny"
    ? { hookEventName: "PreToolUse", permissionDecision: "deny", permissionDecisionReason: `${labels.block}: ${verdict.rule}` }
    : { hookEventName: "PreToolUse", additionalContext: `${labels.warn}: ${verdict.rule}` };
  return JSON.stringify({ hookSpecificOutput: output });
}

function scan(root) {
  const { rules } = load(root);
  const fileRules = rules.filter((r) => r.tools?.some((t) => t === "Write" || t === "Edit"));
  const files = execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8" }).split("\n").filter(Boolean);
  let denied = 0;
  for (const path of files) {
    let content = "";
    try { content = readFileSync(join(root, path), "utf8"); } catch { continue; }
    for (const r of fileRules.filter((r) => matches(r, { path, content }))) {
      console.log(`${r.action === "deny" ? "FAIL" : "warn"} ${path}: ${r.rule}`);
      if (r.action === "deny") denied++;
    }
  }
  console.log(`guardrail scan: ${files.length} files, ${denied} denied`);
  return denied ? 1 : 0;
}

const main = process.argv[1] && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
if (main && process.argv.includes("--scan")) {
  process.exit(scan(process.env.CLAUDE_PROJECT_DIR || process.cwd()));
} else if (main) {
  let input = "";
  process.stdin.setEncoding("utf8");
  process.stdin.on("data", (c) => { input += c; });
  process.stdin.on("end", () => {
    try { process.stdout.write(hook(input)); } catch { /* fail open */ }
    process.exit(0);
  });
}
