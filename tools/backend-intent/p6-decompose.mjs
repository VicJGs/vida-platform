#!/usr/bin/env node
// P6 decomposition generator (deterministic, fail-loud).
// Reads traceability.md, applies the PLAN-p6-frontend-track.md §3 assignment rules,
// emits decomposition-p6.md (per-issue leg sets) + traceability-p6.md (one row per {leg,issue}).
// Node 24. No external writes. Assignment rules are DATA (below) — auditable against the PLAN.
import { readFileSync, writeFileSync } from 'node:fs';

const DIR = 'docs/specs/foundation/backend-intent';
const SRC = `${DIR}/traceability.md`;

// --- Assignment rules (mirror PLAN-p6-frontend-track.md §3 exactly) ---
const RIDE = new Set([
  'xcut-backlinks-search-export:XCU-BSE-14', 'xcut-backlinks-search-export:XCU-BSE-15',
  'xcut-backlinks-search-export:XCU-BSE-16', 'xcut-backlinks-search-export:XCU-BSE-19',
  'xcut-backlinks-search-export:XCU-BSE-20', 'xcut-backlinks-search-export:XCU-BSE-21',
  'xcut-backlinks-search-export:XCU-BSE-22', 'xcut-backlinks-search-export:XCU-BSE-23',
  'xcut-backlinks-search-export:XCU-BSE-24', 'xcut-spaces:XCU-SP-29', 'xcut-views:XCU-14',
]);
const INTEG = new Set([
  'xcut-ingestion-ai:XCU-03u', 'xcut-ingestion-ai:XCU-06u', 'xcut-ingestion-ai:XCU-10u',
  'xcut-ingestion-ai:XCU-16u', 'xcut-ingestion-ai:XCU-18u', 'xcut-ingestion-ai:XCU-19u',
  'xcut-ingestion-ai:XCU-25u', 'xcut-capability:XCU-CAP-17',
]);
const FOLD = {
  'xcut-backlinks-search-export:XCU-BSE-12': 'fe-notes-and-pages',
  'xcut-capability:XCU-CAP-12': 'fe-notes-and-pages',
  'xcut-capability:XCU-CAP-13': 'fe-notes-and-pages',
  'xcut-capability:XCU-CAP-26': 'fe-knowledge',
  'xcut-spaces:XCU-SP-27': 'fe-preferences',
  'xcut-templates:XCU-12': 'fe-preferences',
};
// bucket-slug → fe-issue for the non-xcut module buckets (sessions + pomodoro fold to fe-sessions)
function moduleIssue(slug) {
  if (slug === 'sessions-and-scheduling' || slug === 'pomodoro') return 'fe-sessions';
  return `fe-${slug}`;
}
function assign(itemId, slug) {
  if (RIDE.has(itemId)) return 'fe-shell-integration-wiring';
  if (INTEG.has(itemId)) return 'fe-integrations-ai-surfaces';
  if (FOLD[itemId]) return FOLD[itemId];
  if (slug.startsWith('xcut-')) throw new Error(`FAIL-LOUD: unassigned xcut leg ${itemId} (not in RIDE/INTEG/FOLD)`);
  return moduleIssue(slug);
}

// 24-issue → milestone map (PLAN §3)
const MILESTONE = {
  'fe-preferences': 'M1.2.1', 'fe-sessions': 'M1.2.1', 'fe-journals': 'M1.2.1',
  'fe-notes-and-pages': 'M1.2.1', 'fe-check-ins': 'M1.2.1', 'fe-shell-integration-wiring': 'M1.2.1',
  'fe-finance': 'M1.2.2', 'fe-gamification': 'M1.2.2', 'fe-habits': 'M1.2.2', 'fe-knowledge': 'M1.2.2',
  'fe-books': 'M1.2.2', 'fe-learning-education': 'M1.2.2', 'fe-notifications': 'M1.2.2',
  'fe-projects': 'M1.2.2', 'fe-purposes-and-goals': 'M1.2.2', 'fe-relationships': 'M1.2.2',
  'fe-routines': 'M1.2.2', 'fe-tasks': 'M1.2.2', 'fe-integrations-ai-surfaces': 'M1.2.2',
  'fe-health-core': 'M1.2.3', 'fe-health-nutrition': 'M1.2.3', 'fe-health-training': 'M1.2.3',
  'fe-languages': 'M1.2.3', 'fe-skills': 'M1.2.3',
};

// --- Parse P6 legs from traceability.md ---
const lines = readFileSync(SRC, 'utf8').split('\n');
const legs = []; // {itemId, leg, slug}
for (const ln of lines) {
  if (!ln.startsWith('|')) continue;
  const c = ln.split('|').map((s) => s.trim());
  // c[0]='' , c[1]=item-id, c[2]=leg, c[3]=slug, c[4]=bucket, c[5]=route
  if (c.length < 6) continue;
  if (c[4] !== 'P6:P6') continue;
  const itemId = c[1], leg = c[2], slug = c[3];
  if (!itemId.includes(':')) throw new Error(`FAIL-LOUD: leg key not namespaced (slug:id): ${itemId}`);
  legs.push({ itemId, leg, slug });
}
if (legs.length !== 222) throw new Error(`FAIL-LOUD: expected 222 P6 legs, found ${legs.length}`);

// key = itemId (slug:id) — mandatory namespace (NOT-24 collision guard)
const seen = new Set();
const byIssue = new Map();
const rows = [];
for (const { itemId, leg, slug } of legs) {
  if (seen.has(itemId)) throw new Error(`FAIL-LOUD: duplicate P6 leg key ${itemId}`);
  seen.add(itemId);
  const issue = assign(itemId, slug);
  if (!MILESTONE[issue]) throw new Error(`FAIL-LOUD: issue ${issue} has no milestone home`);
  if (!byIssue.has(issue)) byIssue.set(issue, []);
  byIssue.get(issue).push({ itemId, leg });
  rows.push({ itemId, leg, issue, milestone: MILESTONE[issue] });
}
if (byIssue.size !== 24) throw new Error(`FAIL-LOUD: expected 24 issues, got ${byIssue.size}`);

// --- Emit traceability-p6.md ---
let t = `# P6 — Frontend traceability (leg -> frontend issue)\n\n`;
t += `> Generated by tools/backend-intent/p6-decompose.mjs from traceability.md (222 P6:P6 legs).\n`;
t += `> One row per {slug:id, leg}. Key = slug:id (mandatory namespace — NOT-24 collision). 0 unhomed.\n\n`;
t += `| item-id (slug:id) | leg | frontend issue | milestone |\n|---|---|---|---|\n`;
for (const r of rows.sort((a, b) => a.itemId.localeCompare(b.itemId))) {
  t += `| ${r.itemId} | ${r.leg} | ${r.issue} | ${r.milestone} |\n`;
}
writeFileSync(`${DIR}/traceability-p6.md`, t);

// --- Emit decomposition-p6.md ---
const order = Object.keys(MILESTONE);
let d = `# P6 — Frontend decomposition (24 issues over 222 UI legs)\n\n`;
d += `> Generated by tools/backend-intent/p6-decompose.mjs. Grain: 22 per-module ② tracks + 2 thin cross-cutting.\n`;
d += `> Homing: consumer-pull (a fe-issue rides its mod-twin's wave). Profile: add-frontend-component (Entity Delivery Flow ② track).\n\n`;
let total = 0;
for (const wave of ['M1.2.1', 'M1.2.2', 'M1.2.3']) {
  const issues = order.filter((i) => MILESTONE[i] === wave);
  d += `## ${wave}\n\n| Issue | # legs | leg ids |\n|---|---|---|\n`;
  for (const issue of issues) {
    const set = (byIssue.get(issue) || []).map((x) => x.itemId).sort();
    total += set.length;
    const thin = issue.startsWith('fe-shell') || issue.startsWith('fe-integrations') ? ' **[thin]**' : '';
    d += `| \`${issue}\`${thin} | ${set.length} | ${set.map((s) => s.split(':')[1]).join(', ')} |\n`;
  }
  d += `\n`;
}
d += `**Total legs assigned: ${total} / 222.** Issues: ${byIssue.size} / 24.\n`;
writeFileSync(`${DIR}/decomposition-p6.md`, d);

console.log(`OK — ${legs.length} legs → ${byIssue.size} issues; total assigned ${total}.`);
console.log(`Wrote ${DIR}/decomposition-p6.md + ${DIR}/traceability-p6.md`);
