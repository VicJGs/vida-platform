// @vida/ui — DS-1 token pipeline build script (Style Dictionary → Tamagui + CSS vars).
//
// Uses Style Dictionary (ADR-001) to parse/merge/resolve the 3-layer JSON seed
// (tokens/{primitive,semantic,component}.json) and emits — deterministically, from that single source —
// five targets via CUSTOM formats (Style Dictionary ships no Tamagui format):
//   • variables.css  — design.md §XII CSS custom properties, var() chain preserves the 3 layers (incl. aux font*/shadow/motion)
//   • tokens.ts      — Tamagui createTokens() (primitive layer → color/space/size/radius/zIndex; aux skipped, B9)
//   • themes.ts      — Tamagui light/dark theme objects + light_<Comp>/dark_<Comp> sub-themes
//   • fonts.ts       — DS-2 typography tokens as typed data for DS-4 createFont
//   • motion.ts      — DS-3 motion tokens (duration/easing) as typed data for DS-4 createAnimations (B11)
// Before building, a custom check enforces the design.md §II three-layer indirection and FAILS LOUD (B2).
//
// Run:  pnpm --filter @vida/ui tokens:build   (→ node src/themes/build-tokens.mjs)
// Spec: docs/specs/components/ds-1-token-pipeline/_index.md  (§2 invariants B1–B5, §3 contract, §4 acceptance)
// DS-1 ships THROWAWAY placeholder values — DS-2 authors the real scales directly in the seed (code-first).
// The community Figma file is built later and synced via Figma MCP + a scripter (not Tokens Studio).

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import StyleDictionary from 'style-dictionary'

const HERE = dirname(fileURLToPath(import.meta.url))
const TOKENS_DIR = join(HERE, 'tokens')
const LAYERS = ['primitive', 'semantic', 'component'] // index = layer rank (0 lowest)
const CATEGORIES = ['color', 'space', 'size', 'radius', 'zIndex'] // Tamagui createTokens categories [FACT: @tamagui/core]
// AUX = namespaces that are NOT createTokens categories → routed to CSS (+ typed data), skipped from tokens.ts/themes.ts (B9).
// Factored by destination so each emitter filters by its own sub-list (self-documenting; closes the fonts↔motion leak by construction):
const TYPOGRAPHY = ['fontFamily', 'fontSize', 'fontWeight', 'lineHeight', 'letterSpacing'] // → CSS + fonts.ts (DS-4 createFont)
const MOTION = ['duration', 'easing'] // → CSS + motion.ts (DS-4 createAnimations) — DS-3, B11
const AUX = [...TYPOGRAPHY, 'shadow', ...MOTION] // shadow → CSS only (no typed export); union is what tokens.ts/themes.ts skip
const BANNER = '// GENERATED by build-tokens.mjs — DO NOT EDIT. Edit tokens/*.json and re-run `pnpm tokens:build`.\n'
const CSS_BANNER = '/* GENERATED by build-tokens.mjs — DO NOT EDIT. Edit tokens/*.json and re-run `pnpm tokens:build`. */'

// ── fail loud (B2 / validation) ────────────────────────────────────────────────────────────────────
export class PipelineError extends Error {}
const fail = (msg) => {
  throw new PipelineError(msg)
}

// ── helpers ──────────────────────────────────────────────────────────────────────────────────────────
const isRef = (v) => typeof v === 'string' && /^\{[^}]+\}$/.test(v)
const refTarget = (v) => v.slice(1, -1) // "{color.white}" → "color.white"
const camel = (segs) => segs.map((s, i) => (i === 0 ? s : s.charAt(0).toUpperCase() + s.slice(1))).join('')
const cssVar = (p) => `--${p.split('.').join('-')}` // color.surface.primary → --color-surface-primary (design.md §XII)
const isAuxPath = (p) => AUX.includes(p.split('.')[0]) // typography/shadow — outside the 5 Tamagui categories (B9)
const rankOfFile = (filePath) => LAYERS.findIndex((l) => filePath.includes(`${l}.json`))
const byPathSort = (a, b) => a.localeCompare(b)

// Flatten a layer's nested JSON into Map(pathStr → { path[], value }). A leaf token carries a `value` key.
function flatten(node, path, out) {
  if (node && typeof node === 'object' && 'value' in node) {
    out.set(path.join('.'), { path, value: node.value })
    return out
  }
  if (node && typeof node === 'object') for (const k of Object.keys(node)) flatten(node[k], [...path, k], out)
  return out
}

// ── enforce the three-layer indirection (B1/B2) on in-memory layer objects — Style-Dictionary-independent,
//    so it is unit-testable with fixtures. Takes { primitive, semantic, component } nested JSON objects. ─
export function checkLayers({ primitive, semantic, component }) {
  const perLayer = [primitive, semantic, component].map((obj, rank) => {
    const map = flatten(obj ?? {}, [], new Map())
    if (map.size === 0) fail(`empty seed layer: ${LAYERS[rank]} has no tokens (each layer needs ≥1) [B2]`)
    return map
  })
  const layerOf = new Map()
  const byPath = new Map()
  perLayer.forEach((map, rank) => {
    for (const [p, tok] of map) {
      if (byPath.has(p)) fail(`duplicate token path across layers: ${p} [B1 single-source]`)
      layerOf.set(p, rank)
      byPath.set(p, { ...tok, rank })
    }
  })
  for (const [p, tok] of byPath) {
    if (tok.rank === 0) {
      if (isRef(tok.value)) fail(`primitive token "${p}" holds a reference (${tok.value}); primitives must be literals [B2]`)
      continue
    }
    if (!isRef(tok.value)) fail(`${LAYERS[tok.rank]} token "${p}" holds a raw literal (${JSON.stringify(tok.value)}); it must reference the layer below [B2]`)
    const target = refTarget(tok.value)
    if (!byPath.has(target)) fail(`dangling reference: "${p}" → {${target}} does not resolve [B2]`)
    if (layerOf.get(target) !== tok.rank - 1) {
      fail(`layer-skip: ${LAYERS[tok.rank]} token "${p}" references ${LAYERS[layerOf.get(target)]} "${target}"; it must reference ${LAYERS[tok.rank - 1]} only [B2]`)
    }
  }
  // B8 — 4pt grid, non-negotiable. SCOPED to primitive `space.*` ONLY (radius.full=9999, size, zIndex, line-heights, aux excluded).
  for (const [p, tok] of byPath) {
    if (tok.rank === 0 && p.split('.')[0] === 'space') {
      if (!Number.isInteger(tok.value) || tok.value % 4 !== 0) {
        fail(`off-grid spacing: primitive "${p}" = ${JSON.stringify(tok.value)} is not an integer multiple of 4 [B8 4pt grid]`)
      }
    }
  }
  return { perLayer, byPath }
}

// Read the seed from disk and validate it (fail loud before Style Dictionary runs).
export function validate() {
  const layers = Object.fromEntries(
    LAYERS.map((name) => [name, JSON.parse(readFileSync(join(TOKENS_DIR, `${name}.json`), 'utf8'))]),
  )
  return checkLayers(layers)
}

// ── custom Style Dictionary formats (allTokens carry .path, .filePath, .original.value) ───────────────
// Build a path→token index from allTokens so refs can be walked to their primitive.
const indexTokens = (allTokens) => new Map(allTokens.map((t) => [t.path.join('.'), t]))
function toPrimitivePath(pathStr, index) {
  let cur = pathStr
  for (let i = 0; i < 33; i++) {
    if (rankOfFile(index.get(cur).filePath) === 0) return cur
    cur = refTarget(index.get(cur).original.value)
  }
  fail(`reference cycle at "${pathStr}" [B2]`)
}
function tamaguiRef(primPath) {
  const segs = primPath.split('.')
  if (!CATEGORIES.includes(segs[0])) fail(`primitive "${primPath}" is not under a Tamagui category (${CATEGORIES.join('/')}) [B3]`)
  return { category: segs[0], key: camel(segs.slice(1)) }
}
// tokens.<cat>.<key> — but bracket-notation for non-identifier keys (numeric space/size keys like "8" → tokens.space["8"])
const validId = (k) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k)
const tokenRef = (category, key) => `tokens.${category}${validId(key) ? `.${key}` : `[${JSON.stringify(key)}]`}`

StyleDictionary.registerFormat({
  name: 'vida/css-vars',
  format: ({ dictionary }) => {
    const rows = [...dictionary.allTokens]
      .sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))
      .map((t) => {
        const p = t.path.join('.')
        // primitive → literal; semantic/component → var(--target) so the indirection survives in CSS
        const rhs = isRef(t.original.value) ? `var(${cssVar(refTarget(t.original.value))})` : String(t.value)
        return `  ${cssVar(p)}: ${rhs};`
      })
    return `${CSS_BANNER}\n:root {\n${rows.join('\n')}\n}\n`
  },
})

StyleDictionary.registerFormat({
  name: 'vida/tamagui-tokens',
  format: ({ dictionary }) => {
    const cats = Object.fromEntries(CATEGORIES.map((c) => [c, {}]))
    for (const t of dictionary.allTokens) {
      if (rankOfFile(t.filePath) !== 0) continue // primitive layer only
      if (isAuxPath(t.path.join('.'))) continue // B9 — aux (font*/shadow) go to CSS + fonts.ts, not createTokens
      const { category, key } = tamaguiRef(t.path.join('.'))
      cats[category][key] = t.value
    }
    const body = CATEGORIES.map((cat) => {
      const entries = Object.entries(cats[cat]).sort(([a], [b]) => byPathSort(a, b))
      if (entries.length === 0) return `  ${cat}: { true: 0 },` // Tamagui expects every category present + a `true` default
      const pairs = entries.map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`)
      pairs.push(`true: ${JSON.stringify(entries[0][1])}`) // default per category [FACT: createTokens convention]
      return `  ${cat}: { ${pairs.join(', ')} },`
    }).join('\n')
    return `${BANNER}import { createTokens } from '@tamagui/core'\n\nexport const tokens = createTokens({\n${body}\n})\n`
  },
})

// fe-codec-theme S1 — N preset families × light/dark (B-codec-1, generalizes B7). SCHEME-FIRST names (Tamagui law:
// a theme's scheme = its first `_`-segment, and only light/dark are valid schemes — @tamagui/core@2.6.2
// useThemeState.cjs:312/317). The DEFAULT preset `editorial` keeps the bare `light`/`dark` (+ `light_<Comp>`/
// `dark_<Comp>`) — today's output; non-default presets emit `${mode}_${preset}` + `${mode}_${preset}_<Comp>`. Per-preset
// sub-themes are REQUIRED (the resolver tries ONE `${base}_${componentName}` and does NOT fall back to a bare `<Comp>`).
const PRESETS = [
  // scheme-first theme name ← { light overlay (over the editorial base), dark delta (over that preset's light) }
  { light: 'light', dark: 'dark', lightOverlay: null, darkOverlay: 'semantic.dark.json' }, // editorial (default, bare)
  { light: 'light_reader', dark: 'dark_reader', lightOverlay: 'semantic.reader.json', darkOverlay: 'semantic.reader.dark.json' },
  { light: 'light_quietDesk', dark: 'dark_quietDesk', lightOverlay: 'semantic.quietDesk.json', darkOverlay: 'semantic.quietDesk.dark.json' },
]

StyleDictionary.registerFormat({
  name: 'vida/tamagui-themes',
  format: ({ dictionary }) => {
    const index = indexTokens(dictionary.allTokens)
    const base = {} // editorial light base: semantic key → tokens.<cat>.<key>
    const subs = {} // component name → { key: semanticKey } (the base-theme KEY; resolved to <theme>.<key> at emit)
    for (const t of [...dictionary.allTokens].sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))) {
      const rank = rankOfFile(t.filePath)
      const p = t.path.join('.')
      if (rank === 1) {
        const prim = toPrimitivePath(p, index)
        if (isAuxPath(prim)) continue // B9 — semantic resolving to an aux primitive (e.g. shadow/*) → CSS only, not the theme object
        const { category, key } = tamaguiRef(prim)
        base[camel(t.path)] = tokenRef(category, key)
      } else if (rank === 2) {
        // Component sub-theme: reference the SEMANTIC base-theme KEY (DS-1 spec:113) so <theme>_<Comp>
        // inherits that theme's overlay by construction. Resolving to the PRIMITIVE here (the old drift)
        // collapsed the light/dark indirection. See docs/specs/fixes/component-subtheme-dark-drift/.
        const ref = t.original?.value
        if (!isRef(ref)) fail(`component token "${p}" must reference a semantic token (B2), got ${JSON.stringify(ref)}`)
        const semPath = refTarget(ref) // e.g. "color.brand.emphasis"
        if (isAuxPath(toPrimitivePath(semPath, index))) continue // B9 — aux (shadow/typography) → CSS only, not the theme object
        const Comp = t.path[0].charAt(0).toUpperCase() + t.path[0].slice(1)
        ;(subs[Comp] ??= {})[camel(t.path.slice(1))] = camel(semPath.split('.'))
      }
    }
    // Apply an overlay file (B7, generalized) over a theme object. Loaded BY FILENAME — NOT the SD source glob (F1) —
    // so checkLayers/B1 never see it and it may legitimately reuse base paths. Each entry: isRef + resolves to a loaded
    // primitive (aux → CSS only, skipped), else FAIL LOUD. Missing file → no overrides (honest placeholder). Merge is
    // per-LEAF, so a preset overlay may partially override a group (e.g. text.primary/muted) and inherit the rest.
    const applyOverlay = (src, filename) => {
      const out = { ...src }
      let count = 0
      if (!filename) return { obj: out, count }
      try {
        const overlay = flatten(JSON.parse(readFileSync(join(TOKENS_DIR, filename), 'utf8')), [], new Map())
        for (const [p, tok] of [...overlay].sort(([a], [b]) => byPathSort(a, b))) {
          if (!isRef(tok.value)) fail(`overlay "${filename}" entry "${p}" holds a raw literal (${JSON.stringify(tok.value)}); it must reference a primitive [B7]`)
          const prim = refTarget(tok.value)
          if (!index.has(prim)) fail(`overlay "${filename}" entry "${p}" → {${prim}} does not resolve to a loaded primitive [B7]`)
          if (isAuxPath(prim)) continue // e.g. dark shadow = border-based (design.md §V) → CSS at DS-4, not the theme object
          const { category, key } = tamaguiRef(toPrimitivePath(prim, index))
          out[camel(p.split('.'))] = tokenRef(category, key)
          count++
        }
      } catch (e) {
        if (e instanceof PipelineError) throw e // real B7 violation — fail loud
        // else: overlay file absent → no overrides (honest placeholder)
      }
      return { obj: out, count }
    }
    // Compose the 6 base themes. Precedence per non-default preset: base < semantic.<preset>.json < semantic.<preset>.dark.json.
    const themes = {}
    let totalOverrides = 0
    for (const P of PRESETS) {
      const lightTheme = P.lightOverlay ? applyOverlay(base, P.lightOverlay) : { obj: { ...base }, count: 0 }
      const darkTheme = applyOverlay(lightTheme.obj, P.darkOverlay)
      themes[P.light] = lightTheme.obj
      themes[P.dark] = darkTheme.obj
      totalOverrides += lightTheme.count + darkTheme.count
    }
    const obj = (o) => `{ ${Object.entries(o).map(([k, v]) => `${JSON.stringify(k)}: ${v}`).join(', ')} }`
    const note =
      totalOverrides > 0
        ? `// ${Object.keys(themes).length} scheme-first base themes (3 presets × light/dark) + per-theme <Comp> sub-themes — parallel dark/preset VALUES (B-codec-1/B7). Theme-switch MECHANISM = DS-4/fe-codec S3.`
        : '// PLACEHOLDER: no overlays → all themes == editorial base. Overlays supply parallel preset/dark VALUES; MECHANISM = DS-4.'
    const out = [`${BANNER}import { tokens } from './tokens'\n`, note]
    for (const [name, themeObj] of Object.entries(themes)) out.push(`export const ${name} = ${obj(themeObj)}\n`)
    // Component sub-themes — editorial base schemes ONLY (light/dark). The per-preset `<mode>_<preset>_<Comp>` set is
    // NOT generated: it never resolved (Tamagui names it combined `t_<preset>_<Comp>`, the app applies `t_<preset>`+`t_<Comp>`
    // separately) and components now read the preset via DIRECT semantic tokens ($colorBrand*/$colorSurface*/…), which
    // inherit the active preset at component scope (a component sub-theme emits only its OWN keys, not the semantic vars).
    // These base sub-themes remain only as scoping scaffolding so `name="<Comp>"` + portal `<Theme name="<Comp>">` resolve;
    // their keys are no longer consumed for preset-sensitive color. [fe-codec-theme — accent-inherit fix, STRUCTURAL §XXVIII]
    const refBase = (sub, theme) =>
      Object.fromEntries(Object.entries(sub).map(([k, semKey]) => [k, `${theme}.${semKey}`]))
    for (const theme of ['light', 'dark']) {
      for (const Comp of Object.keys(subs).sort()) {
        out.push(`export const ${theme}_${Comp} = ${obj(refBase(subs[Comp], theme))}`)
      }
    }
    return out.join('\n')
  },
})

// Typography tokens as typed plain data for DS-4's createFont (fonts are NOT createTokens categories — B9).
StyleDictionary.registerFormat({
  name: 'vida/fonts',
  format: ({ dictionary }) => {
    const groups = {}
    for (const t of [...dictionary.allTokens].sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))) {
      if (rankOfFile(t.filePath) !== 0) continue // primitive layer only
      const [ns, ...rest] = t.path
      if (!TYPOGRAPHY.includes(ns)) continue // typography aux only — shadow → CSS-only, motion → motion.ts (B9/B11)
      ;(groups[ns] ??= {})[camel(rest)] = t.value
    }
    const body = Object.keys(groups)
      .sort()
      .map((ns) => `  ${ns}: { ${Object.entries(groups[ns]).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(', ')} },`)
      .join('\n')
    return `${BANNER}\n// Typography tokens as typed data — DS-4 feeds these to Tamagui createFont (fonts ⊄ createTokens categories).\nexport const fonts = {\n${body}\n} as const\n`
  },
})

// Motion tokens as typed plain data for DS-4's createAnimations (duration/easing are NOT createTokens categories — B9/B11).
// Mirrors vida/fonts verbatim, including BOTH sort layers (tokens sorted by path before grouping; namespaces sorted) for
// determinism (B4). durations = unitless numbers (ms; unit reconciliation → DS-4); easings = CSS cubic-bezier/linear strings.
StyleDictionary.registerFormat({
  name: 'vida/motion',
  format: ({ dictionary }) => {
    const groups = {}
    for (const t of [...dictionary.allTokens].sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))) {
      if (rankOfFile(t.filePath) !== 0) continue // primitive layer only
      const [ns, ...rest] = t.path
      if (!MOTION.includes(ns)) continue // motion aux only (duration/easing)
      ;(groups[ns] ??= {})[camel(rest)] = t.value
    }
    const body = Object.keys(groups)
      .sort()
      .map((ns) => `  ${ns}: { ${Object.entries(groups[ns]).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(', ')} },`)
      .join('\n')
    return `${BANNER}\n// Motion tokens as typed data — DS-4 feeds these to Tamagui createAnimations (motion ⊄ createTokens categories).\nexport const motion = {\n${body}\n} as const\n`
  },
})

// Shadow tokens as typed plain data (shadow is aux → NOT a createTokens category, B9). Emitted as a typed export the
// same way motion.ts is, because a TS consumer now needs the values: UI-1 Card injects box-shadow via CSS (elevation
// = opacity of a raised-shadow overlay, B12) and reads these literals — pipeline stays the single source (no drift).
// First shadow consumer (DEF-U5-e); shadow is a single namespace, so this flattens `shadow.<level>` (no `ns` key).
StyleDictionary.registerFormat({
  name: 'vida/shadow',
  format: ({ dictionary }) => {
    const entries = {}
    for (const t of [...dictionary.allTokens].sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))) {
      if (rankOfFile(t.filePath) !== 0) continue // primitive layer only
      const [ns, ...rest] = t.path
      if (ns !== 'shadow') continue // shadow aux only
      entries[camel(rest)] = t.value
    }
    const body = Object.entries(entries)
      .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
      .join('\n')
    return `${BANNER}\n// Shadow tokens as typed data — elevation box-shadow literals for injected component CSS (shadow ⊄ createTokens categories, B9). First consumer: UI-1 Card (DEF-U5-e).\nexport const shadow = {\n${body}\n} as const\n`
  },
})

// ── build ─────────────────────────────────────────────────────────────────────────────────────────────
export async function build() {
  validate() // fail loud BEFORE Style Dictionary runs (B2)
  const sd = new StyleDictionary({
    source: LAYERS.map((l) => join(TOKENS_DIR, `${l}.json`)), // explicit 3-file list — keeps semantic.dark.json overlay OUT of the source (F1: no phantom rank −1 layer)
    log: { errors: 'throw', warnings: 'disabled', verbosity: 'silent' }, // dangling refs throw too (belt & suspenders w/ validate)
    platforms: {
      vida: {
        transforms: [], // values are already final; no unit/color transforms wanted
        buildPath: `${HERE}/`,
        files: [
          { destination: 'variables.css', format: 'vida/css-vars' },
          { destination: 'tokens.ts', format: 'vida/tamagui-tokens' },
          { destination: 'themes.ts', format: 'vida/tamagui-themes' },
          { destination: 'fonts.ts', format: 'vida/fonts' },
          { destination: 'motion.ts', format: 'vida/motion' },
          { destination: 'shadow.ts', format: 'vida/shadow' },
        ],
      },
    },
  })
  await sd.buildAllPlatforms()
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  build()
    .then(() => console.log('✓ tokens:build — variables.css, tokens.ts, themes.ts, fonts.ts, motion.ts, shadow.ts written'))
    .catch((err) => {
      console.error(`✗ tokens:build failed: ${err.message}`)
      process.exit(1)
    })
}
