// @vida/ui — DS-1 token pipeline build script (Style Dictionary → Tamagui + CSS vars).
//
// Uses Style Dictionary (ADR-001) to parse/merge/resolve the 3-layer JSON seed
// (tokens/{primitive,semantic,component}.json) and emits — deterministically, from that single source —
// three targets via CUSTOM formats (Style Dictionary ships no Tamagui format):
//   • variables.css  — design.md §XII CSS custom properties, var() chain preserves the 3 layers
//   • tokens.ts      — Tamagui createTokens() (primitive layer → color/space/size/radius/zIndex)
//   • themes.ts      — Tamagui light/dark theme objects + light_<Comp>/dark_<Comp> sub-themes
// Before building, a custom check enforces the design.md §II three-layer indirection and FAILS LOUD (B2).
//
// Run:  pnpm --filter @vida/ui tokens:build   (→ node src/themes/build-tokens.mjs)
// Spec: docs/specs/components/ds-1-token-pipeline/_index.md  (§2 invariants B1–B5, §3 contract, §4 acceptance)
// DS-1 ships THROWAWAY placeholder values — DS-2 replaces the seed with the real Figma → Tokens Studio export.

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import StyleDictionary from 'style-dictionary'

const HERE = dirname(fileURLToPath(import.meta.url))
const TOKENS_DIR = join(HERE, 'tokens')
const LAYERS = ['primitive', 'semantic', 'component'] // index = layer rank (0 lowest)
const CATEGORIES = ['color', 'space', 'size', 'radius', 'zIndex'] // Tamagui createTokens categories [FACT: @tamagui/core]
const BANNER = '// GENERATED by build-tokens.mjs — DO NOT EDIT. Edit tokens/*.json and re-run `pnpm tokens:build`.\n'
const CSS_BANNER = '/* GENERATED by build-tokens.mjs — DO NOT EDIT. Edit tokens/*.json and re-run `pnpm tokens:build`. */'

// ── fail loud (B2 / validation) ────────────────────────────────────────────────────────────────────
export class PipelineError extends Error {}
const fail = (msg) => {
  throw new PipelineError(msg)
}

// ── helpers ──────────────────────────────────────────────────────────────────────────────────────────
const isRef = (v) => typeof v === 'string' && /^\{[^}]+\}$/.test(v)
const refTarget = (v) => v.slice(1, -1) // "{color.white}" → "color.white"
const camel = (segs) => segs.map((s, i) => (i === 0 ? s : s.charAt(0).toUpperCase() + s.slice(1))).join('')
const cssVar = (p) => `--${p.split('.').join('-')}` // color.surface.primary → --color-surface-primary (design.md §XII)
const rankOfFile = (filePath) => LAYERS.findIndex((l) => filePath.includes(`${l}.json`))
const byPathSort = (a, b) => a.localeCompare(b)

// Flatten a layer's nested JSON into Map(pathStr → { path[], value }). A leaf token carries a `value` key.
function flatten(node, path, out) {
  if (node && typeof node === 'object' && 'value' in node) {
    out.set(path.join('.'), { path, value: node.value })
    return out
  }
  if (node && typeof node === 'object') for (const k of Object.keys(node)) flatten(node[k], [...path, k], out)
  return out
}

// ── enforce the three-layer indirection (B1/B2) on in-memory layer objects — Style-Dictionary-independent,
//    so it is unit-testable with fixtures. Takes { primitive, semantic, component } nested JSON objects. ─
export function checkLayers({ primitive, semantic, component }) {
  const perLayer = [primitive, semantic, component].map((obj, rank) => {
    const map = flatten(obj ?? {}, [], new Map())
    if (map.size === 0) fail(`empty seed layer: ${LAYERS[rank]} has no tokens (each layer needs ≥1) [B2]`)
    return map
  })
  const layerOf = new Map()
  const byPath = new Map()
  perLayer.forEach((map, rank) => {
    for (const [p, tok] of map) {
      if (byPath.has(p)) fail(`duplicate token path across layers: ${p} [B1 single-source]`)
      layerOf.set(p, rank)
      byPath.set(p, { ...tok, rank })
    }
  })
  for (const [p, tok] of byPath) {
    if (tok.rank === 0) {
      if (isRef(tok.value)) fail(`primitive token "${p}" holds a reference (${tok.value}); primitives must be literals [B2]`)
      continue
    }
    if (!isRef(tok.value)) fail(`${LAYERS[tok.rank]} token "${p}" holds a raw literal (${JSON.stringify(tok.value)}); it must reference the layer below [B2]`)
    const target = refTarget(tok.value)
    if (!byPath.has(target)) fail(`dangling reference: "${p}" → {${target}} does not resolve [B2]`)
    if (layerOf.get(target) !== tok.rank - 1) {
      fail(`layer-skip: ${LAYERS[tok.rank]} token "${p}" references ${LAYERS[layerOf.get(target)]} "${target}"; it must reference ${LAYERS[tok.rank - 1]} only [B2]`)
    }
  }
  return { perLayer, byPath }
}

// Read the seed from disk and validate it (fail loud before Style Dictionary runs).
export function validate() {
  const layers = Object.fromEntries(
    LAYERS.map((name) => [name, JSON.parse(readFileSync(join(TOKENS_DIR, `${name}.json`), 'utf8'))]),
  )
  return checkLayers(layers)
}

// ── custom Style Dictionary formats (allTokens carry .path, .filePath, .original.value) ───────────────
// Build a path→token index from allTokens so refs can be walked to their primitive.
const indexTokens = (allTokens) => new Map(allTokens.map((t) => [t.path.join('.'), t]))
function toPrimitivePath(pathStr, index) {
  let cur = pathStr
  for (let i = 0; i < 33; i++) {
    if (rankOfFile(index.get(cur).filePath) === 0) return cur
    cur = refTarget(index.get(cur).original.value)
  }
  fail(`reference cycle at "${pathStr}" [B2]`)
}
function tamaguiRef(primPath) {
  const segs = primPath.split('.')
  if (!CATEGORIES.includes(segs[0])) fail(`primitive "${primPath}" is not under a Tamagui category (${CATEGORIES.join('/')}) [B3]`)
  return { category: segs[0], key: camel(segs.slice(1)) }
}

StyleDictionary.registerFormat({
  name: 'vida/css-vars',
  format: ({ dictionary }) => {
    const rows = [...dictionary.allTokens]
      .sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))
      .map((t) => {
        const p = t.path.join('.')
        // primitive → literal; semantic/component → var(--target) so the indirection survives in CSS
        const rhs = isRef(t.original.value) ? `var(${cssVar(refTarget(t.original.value))})` : String(t.value)
        return `  ${cssVar(p)}: ${rhs};`
      })
    return `${CSS_BANNER}\n:root {\n${rows.join('\n')}\n}\n`
  },
})

StyleDictionary.registerFormat({
  name: 'vida/tamagui-tokens',
  format: ({ dictionary }) => {
    const cats = Object.fromEntries(CATEGORIES.map((c) => [c, {}]))
    for (const t of dictionary.allTokens) {
      if (rankOfFile(t.filePath) !== 0) continue // primitive layer only
      const { category, key } = tamaguiRef(t.path.join('.'))
      cats[category][key] = t.value
    }
    const body = CATEGORIES.map((cat) => {
      const entries = Object.entries(cats[cat]).sort(([a], [b]) => byPathSort(a, b))
      if (entries.length === 0) return `  ${cat}: { true: 0 },` // Tamagui expects every category present + a `true` default
      const pairs = entries.map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`)
      pairs.push(`true: ${JSON.stringify(entries[0][1])}`) // default per category [FACT: createTokens convention]
      return `  ${cat}: { ${pairs.join(', ')} },`
    }).join('\n')
    return `${BANNER}import { createTokens } from '@tamagui/core'\n\nexport const tokens = createTokens({\n${body}\n})\n`
  },
})

StyleDictionary.registerFormat({
  name: 'vida/tamagui-themes',
  format: ({ dictionary }) => {
    const index = indexTokens(dictionary.allTokens)
    const base = {} // semantic → base light/dark keys, value = tokens.<cat>.<key>
    const subs = {} // component name → { key: tokens.<cat>.<key> }
    for (const t of [...dictionary.allTokens].sort((a, b) => byPathSort(a.path.join('.'), b.path.join('.')))) {
      const rank = rankOfFile(t.filePath)
      const p = t.path.join('.')
      if (rank === 1) {
        const { category, key } = tamaguiRef(toPrimitivePath(p, index))
        base[camel(t.path)] = `tokens.${category}.${key}`
      } else if (rank === 2) {
        const Comp = t.path[0].charAt(0).toUpperCase() + t.path[0].slice(1)
        const { category, key } = tamaguiRef(toPrimitivePath(p, index))
        ;(subs[Comp] ??= {})[camel(t.path.slice(1))] = `tokens.${category}.${key}`
      }
    }
    const obj = (o) => `{ ${Object.entries(o).map(([k, v]) => `${JSON.stringify(k)}: ${v}`).join(', ')} }`
    const out = [
      `${BANNER}import { tokens } from './tokens'\n`,
      '// PLACEHOLDER light/dark values (identical) — DS-2 supplies the real, parallel-designed dark theme.',
      `export const light = ${obj(base)}\n`,
      `export const dark = ${obj(base)}\n`,
    ]
    for (const Comp of Object.keys(subs).sort()) {
      out.push(`export const light_${Comp} = ${obj(subs[Comp])}`)
      out.push(`export const dark_${Comp} = ${obj(subs[Comp])}\n`)
    }
    return out.join('\n')
  },
})

// ── build ─────────────────────────────────────────────────────────────────────────────────────────────
export async function build() {
  validate() // fail loud BEFORE Style Dictionary runs (B2)
  const sd = new StyleDictionary({
    source: [join(TOKENS_DIR, '*.json')],
    log: { errors: 'throw', warnings: 'disabled', verbosity: 'silent' }, // dangling refs throw too (belt & suspenders w/ validate)
    platforms: {
      vida: {
        transforms: [], // values are already final; no unit/color transforms wanted
        buildPath: `${HERE}/`,
        files: [
          { destination: 'variables.css', format: 'vida/css-vars' },
          { destination: 'tokens.ts', format: 'vida/tamagui-tokens' },
          { destination: 'themes.ts', format: 'vida/tamagui-themes' },
        ],
      },
    },
  })
  await sd.buildAllPlatforms()
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  build()
    .then(() => console.log('✓ tokens:build — variables.css, tokens.ts, themes.ts written'))
    .catch((err) => {
      console.error(`✗ tokens:build failed: ${err.message}`)
      process.exit(1)
    })
}
